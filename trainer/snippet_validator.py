def extract_python_snippets(content: str, max_lines: int = 35) -> list[str]:
    """Extract functions, classes, and substantive top-level blocks from Python source code."""
    chunks = []
    try:
        tree = ast.parse(content)
    except Exception:
        return []

    lines = content.splitlines()
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            start = node.lineno - 1
            end = getattr(node, "end_lineno", None)
            if end is None:
                continue
            block_lines = lines[start:end]
            chunk = clean_snippet_code("\n".join(block_lines))
            ok, _ = is_valid_snippet(chunk, "python")
            if ok and len(chunk.splitlines()) <= max_lines:
                chunks.append(chunk)

    # Fallback for scripts without def/class (top-level statements)
    if not chunks and tree.body:
        for diff, min_l, max_l in [("easy", 5, 10), ("medium", 12, 19), ("hard", 21, 32)]:
            for i in range(0, len(lines), max_l):
                window = lines[i : i + max_l]
                if min_l <= len(window) <= max_l:
                    chunk = clean_snippet_code("\n".join(window))
                    ok, _ = is_valid_snippet(chunk, "python")
                    if ok:
                        chunks.append(chunk)

    return chunks


def extract_brace_snippets(content: str, language_slug: str, max_lines: int = 35) -> list[str]:
    """Extract complete methods/functions and compact classes from brace-delimited languages."""
    lines = content.splitlines()
    chunks = []

    if language_slug in ("java", "csharp"):
        sig_pattern = re.compile(
            r"^\s*(class\s+\w+|namespace\s+\w+|(public|private|protected|static|final|async|override|virtual|\w+<[\w\s,]+>)\s+[\w<>,\[\]\s]+\s+\w+\s*\()"
        )
    elif language_slug == "javascript":
        sig_pattern = re.compile(
            r"^\s*(class\s+\w+|(export\s+)?(async\s+)?function\s+\w|^\s*(export\s+)?(const|let|var)\s+\w+\s*=\s*(async\s+)?\([^)]*\)\s*=>|^\s*(const|let|var)\s+\w+\s*=\s*(async\s+)?function)"
        )
    elif language_slug == "go":
        sig_pattern = re.compile(r"^func\s+(\([^)]+\)\s+)?\w+\s*\(|^type\s+\w+\s+(struct|interface)\s*\{")
    elif language_slug == "php":
        sig_pattern = re.compile(r"^\s*(class\s+\w+|(public|private|protected|static)?\s*function\s+\w+\s*\()")
    elif language_slug == "cpp":
        sig_pattern = re.compile(
            r"^\s*(class\s+\w+|struct\s+\w+|(void|int|bool|double|float|auto|std::\w+|template<[^>]+>\s+\w+)\s+\w+\s*\()"
        )
    else:
        sig_pattern = re.compile(r"^\s*(function|\w+)\s+\w+\s*\(")

    i = 0
    while i < len(lines):
        line = lines[i]
        if sig_pattern.search(line):
            depth = 0
            found_open = False
            start_idx = i
            end_idx = None
            for j in range(i, min(len(lines), i + max_lines + 5)):
                l = lines[j]
                for char in l:
                    if char == "{":
                        depth += 1
                        found_open = True
                    elif char == "}":
                        depth -= 1
                if found_open and depth == 0:
                    end_idx = j
                    break

            if end_idx is not None:
                block_lines = lines[start_idx : end_idx + 1]
                chunk = clean_snippet_code("\n".join(block_lines))
                ok, _ = is_valid_snippet(chunk, language_slug)
                if ok and len(chunk.splitlines()) <= max_lines:
                    chunks.append(chunk)
                i = end_idx + 1
                continue
        i += 1

    return chunks


def extract_css_snippets(content: str, max_lines: int = 35) -> list[str]:
    """Extract complete CSS rules."""
    cleaned = re.sub(r"/\*[\s\S]*?\*/", "", content)
    pattern = re.compile(r"([^{}]+)\s*\{([^}]+)\}")
    rules = []
    for match in pattern.finditer(cleaned):
        selector = match.group(1).strip()
        body = match.group(2).strip()
        if not selector or not body:
            continue
        props = [p.strip() for p in body.split(";") if p.strip()]
        if not props or len(props) > 18:
            continue
        rule = f"{selector} {{\n" + "\n".join(f"    {p};" for p in props) + "\n}"
        ok, _ = is_valid_snippet(rule, "css")
        if ok and len(rule.splitlines()) <= max_lines:
            rules.append(rule)
    return rules


def extract_sql_snippets(content: str, max_lines: int = 35) -> list[str]:
    """Extract clean SQL statements (rejecting Jinja macros)."""
    if "{%" in content or "{{" in content or "{#" in content:
        return []
    queries = []
    statements = content.split(";")
    for stmt in statements:
        s = clean_snippet_code(stmt)
        if not s:
            continue
        s = s + ";"
        ok, _ = is_valid_snippet(s, "sql")
        if ok and len(s.splitlines()) <= max_lines:
            queries.append(s)
    return queries


def extract_bash_snippets(content: str, max_lines: int = 35) -> list[str]:
    """Extract Bash functions and structured compound blocks (if-fi, loops)."""
    lines = content.splitlines()
    chunks = []
    start_pattern = re.compile(r"^\s*(function\s+\w+|\w+\s*\(\)\s*\{|if\s+\[|for\s+\w+|while\s+|case\s+)")

    i = 0
    while i < len(lines):
        line = lines[i]
        if start_pattern.search(line):
            # Check for brace block
            if "{" in line:
                depth = 0
                found_open = False
                end_idx = None
                for j in range(i, min(len(lines), i + max_lines + 5)):
                    for char in lines[j]:
                        if char == "{":
                            depth += 1
                            found_open = True
                        elif char == "}":
                            depth -= 1
                    if found_open and depth == 0:
                        end_idx = j
                        break
                if end_idx is not None:
                    block_lines = lines[i : end_idx + 1]
                    chunk = clean_snippet_code("\n".join(block_lines))
                    ok, _ = is_valid_snippet(chunk, "bash")
                    if ok and len(chunk.splitlines()) <= max_lines:
                        chunks.append(chunk)
                    i = end_idx + 1
                    continue
            else:
                # Check for if-fi, for-done, while-done
                end_token = None
                if re.match(r"^\s*if\s+", line):
                    end_token = "fi"
                elif re.match(r"^\s*(for|while)\s+", line):
                    end_token = "done"
                elif re.match(r"^\s*case\s+", line):
                    end_token = "esac"

                if end_token:
                    end_idx = None
                    for j in range(i + 3, min(len(lines), i + max_lines + 5)):
                        if lines[j].strip() == end_token or lines[j].strip().startswith(end_token + ";"):
                            end_idx = j
                            break
                    if end_idx is not None:
                        block_lines = lines[i : end_idx + 1]
                        chunk = clean_snippet_code("\n".join(block_lines))
                        ok, _ = is_valid_snippet(chunk, "bash")
                        if ok and len(chunk.splitlines()) <= max_lines:
                            chunks.append(chunk)
                        i = end_idx + 1
                        continue
        i += 1
    return chunks


def extract_html_snippets(content: str, max_lines: int = 35) -> list[str]:
    """Extract semantic HTML elements."""
    if "{%" in content or "{{" in content:
        return []
    tag_pattern = re.compile(
        r"<(form|nav|table|section|article|header|footer|div)\b[^>]*>[\s\S]*?</\1>",
        re.IGNORECASE
    )
    chunks = []
    for match in tag_pattern.finditer(content):
        chunk = clean_snippet_code(match.group(0))
        ok, _ = is_valid_snippet(chunk, "html")
        if ok and len(chunk.splitlines()) <= max_lines:
            chunks.append(chunk)
    return chunks


def extract_code_snippets(content: str, language_slug: str, max_lines: int = 35) -> list[str]:
    """Unified entry point to extract valid snippets for a given language."""
    if language_slug == "python":
        return extract_python_snippets(content, max_lines)
    elif language_slug in ("java", "javascript", "cpp", "csharp", "php", "go"):
        return extract_brace_snippets(content, language_slug, max_lines)
    elif language_slug == "css":
        return extract_css_snippets(content, max_lines)
    elif language_slug == "sql":
        return extract_sql_snippets(content, max_lines)
    elif language_slug == "html":
        return extract_html_snippets(content, max_lines)
    elif language_slug == "bash":
        return extract_bash_snippets(content, max_lines)
    return []


def extract_categorized_snippets(content: str, language_slug: str) -> dict[str, list[str]]:
    """
    Extract snippets categorized into easy (4-10 lines), medium (11-20 lines),
    and hard (21-35 lines).
    """
    chunks = extract_code_snippets(content, language_slug)
    categorized = {"easy": [], "medium": [], "hard": []}
    for chunk in chunks:
        n = len(chunk.splitlines())
        if 4 <= n <= 10:
            categorized["easy"].append(chunk)
        elif 11 <= n <= 20:
            categorized["medium"].append(chunk)
        elif 21 <= n <= 35:
            categorized["hard"].append(chunk)
    return categorized

